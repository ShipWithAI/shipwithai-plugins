#!/usr/bin/env python3
"""Compute the harness's self-improvement metrics from the ledger — proof it's compounding.

Reads `harness/ledger/findings.jsonl` and renders three numbers (spec §8) to
`harness/ledger/metrics.md`:

  1. Iterations-to-pass per screen  — max loop `iteration` that still surfaced findings.
     Lower = converged faster. Trend ↓ as prevention improves.
  2. First-pass yield               — fraction of screens with ZERO Tier-1 findings at
     iteration 1 (came in structurally clean on first render). Trend ↑.
  3. Recurrence after deposit       — per promoted category, findings still OPEN after it was
     deposited. Should → 0; if a category keeps recurring, the promotion didn't stick → move it
     down a tier. This is also the promotion *signal*.

Pure read-only analysis (the report is regenerated each run → gitignored). Usage:

    python3 harness/bin/metrics_ledger.py

Modeling note: a finding is "fixed" by ABSENCE in later iterations (a clean re-render records
nothing), and `resolved`/`deposit` mark promotion. So "open" = not-yet-fixed *or* not-yet-marked;
the three metrics above are defined to not depend on a fix marking the loop doesn't currently do.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

DEFAULT_LEDGER = "harness/ledger/findings.jsonl"
DEFAULT_OUT = "harness/ledger/metrics.md"


def load_findings(ledger_path) -> list:
    p = Path(ledger_path)
    if not p.exists():
        return []
    out = []
    for line in p.read_text(encoding="utf-8").splitlines():
        s = line.strip()
        if not s:
            continue
        try:
            out.append(json.loads(s))
        except json.JSONDecodeError:
            print(f"warning: skipping malformed ledger line: {s[:80]}", file=sys.stderr)
    return out


def is_open(f: dict) -> bool:
    return not f.get("resolved", False) and f.get("deposit") in (None, "")


def _iter(f: dict) -> int:
    return f.get("iteration") or 1


def iterations_to_pass(findings: list) -> dict:
    """screen -> {iters, open} where iters = max iteration that recorded a finding."""
    by_screen = {}
    for f in findings:
        s = f.get("screen", "unknown")
        d = by_screen.setdefault(s, {"iters": 0, "open": 0})
        d["iters"] = max(d["iters"], _iter(f))
        if is_open(f):
            d["open"] += 1
    return by_screen


def first_pass_yield(findings: list):
    """(clean_screens, dirty_screens) — clean = no Tier-1 finding at iteration 1."""
    screens = {f.get("screen", "unknown") for f in findings}
    dirty = {
        f.get("screen", "unknown")
        for f in findings
        if f.get("tier") == 1 and _iter(f) == 1
    }
    clean = screens - dirty
    return clean, dirty, screens


def recurrence_after_deposit(findings: list) -> dict:
    """category -> {labels, closed, recurred} for every category that has been deposited."""
    cats = {f.get("category") for f in findings if f.get("deposit")}
    out = {}
    for cat in cats:
        rows = [f for f in findings if f.get("category") == cat]
        out[cat] = {
            "labels": sorted({f["deposit"] for f in rows if f.get("deposit")}),
            "closed": sum(1 for f in rows if f.get("deposit")),
            "recurred": sum(1 for f in rows if is_open(f)),  # open after deposit closed the rest
        }
    return out


def render(findings: list) -> str:
    L = []
    L.append("# UI harness metrics")
    L.append("")
    L.append("> Generated by `harness/bin/metrics_ledger.py` from `harness/ledger/findings.jsonl`.")
    L.append("> Regenerated each run (gitignored). The ledger is the durable history; this is a snapshot.")
    L.append("")

    if not findings:
        L.append("_No findings yet — run `/ui-iterate <Screen>` to populate the ledger._")
        L.append("")
        return "\n".join(L)

    total = len(findings)
    open_n = sum(1 for f in findings if is_open(f))
    deposited_n = sum(1 for f in findings if f.get("deposit"))
    screens = sorted({f.get("screen", "unknown") for f in findings})
    cats = sorted({f.get("category", "unknown") for f in findings})
    L.append(f"**Ledger:** {total} findings · {len(screens)} screen(s) · {len(cats)} categor(ies) · "
             f"{deposited_n} deposited · {open_n} open")
    L.append("")

    # 1. Iterations-to-pass
    L.append("## 1. Iterations-to-pass per screen — trend ↓")
    L.append("")
    its = iterations_to_pass(findings)
    L.append("| screen | iterations | status |")
    L.append("|---|---|---|")
    for s in sorted(its):
        d = its[s]
        status = "clean" if d["open"] == 0 else f"{d['open']} open"
        L.append(f"| `{s}` | {d['iters']} | {status} |")
    if its:
        mean = sum(d["iters"] for d in its.values()) / len(its)
        L.append("")
        L.append(f"Mean iterations across {len(its)} screen(s): **{mean:.2f}** (lower is better).")
    L.append("")

    # 2. First-pass yield
    L.append("## 2. First-pass yield — trend ↑")
    L.append("")
    clean, dirty, all_screens = first_pass_yield(findings)
    pct = (len(clean) / len(all_screens) * 100) if all_screens else 0.0
    L.append(f"**{len(clean)} / {len(all_screens)}** screen(s) had zero Tier-1 findings at iteration 1 "
             f"= **{pct:.0f}%**.")
    L.append("")
    L.append(f"- clean on first render: {', '.join(f'`{s}`' for s in sorted(clean)) or '_none_'}")
    L.append(f"- structural blocker at iter 1: {', '.join(f'`{s}`' for s in sorted(dirty)) or '_none_'}")
    L.append("")

    # 3. Recurrence after deposit
    L.append("## 3. Recurrence after deposit — should → 0")
    L.append("")
    rec = recurrence_after_deposit(findings)
    if not rec:
        L.append("_Nothing promoted yet — run `/ui-distill` once a category recurs._")
    else:
        L.append("| category | closed by deposit | recurred after | verdict |")
        L.append("|---|---|---|---|")
        for cat in sorted(rec):
            d = rec[cat]
            ok = d["recurred"] == 0
            verdict = "✓ stuck" if ok else "⚠️ recurring — promotion didn't stick; move down a tier"
            L.append(f"| `{cat}` | {d['closed']} | {d['recurred']} | {verdict} |")
        flagged = [c for c, d in rec.items() if d["recurred"] > 0]
        if flagged:
            L.append("")
            L.append(f"⚠️ **{len(flagged)} categor(ies) recurred after promotion:** "
                     f"{', '.join(f'`{c}`' for c in sorted(flagged))} — the deposit isn't holding; "
                     f"harden it further (e.g. evaluator rubric line → deterministic gate → structural).")
    L.append("")
    return "\n".join(L)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ledger", default=DEFAULT_LEDGER, help=f"ledger path (default: {DEFAULT_LEDGER})")
    ap.add_argument("--out", default=DEFAULT_OUT, help=f"metrics file to write (default: {DEFAULT_OUT})")
    args = ap.parse_args(argv)

    findings = load_findings(args.ledger)
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text(render(findings), encoding="utf-8")

    if not findings:
        print(f"ledger empty -> {args.out} (no metrics yet)")
        return 0
    clean, _, all_screens = first_pass_yield(findings)
    its = iterations_to_pass(findings)
    mean = sum(d["iters"] for d in its.values()) / len(its) if its else 0
    rec = recurrence_after_deposit(findings)
    flagged = [c for c, d in rec.items() if d["recurred"] > 0]
    print(f"{len(findings)} findings -> {args.out}")
    print(f"  iterations-to-pass (mean): {mean:.2f} across {len(its)} screen(s)")
    print(f"  first-pass yield: {len(clean)}/{len(all_screens)} screens")
    print(f"  recurrence-after-deposit flags: {len(flagged)}" + (f" ({', '.join(flagged)})" if flagged else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
